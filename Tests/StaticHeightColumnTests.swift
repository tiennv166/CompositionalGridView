import Foundation
import Nimble
import Quick
import UIKit
@testable import CompositionalGridView

final class StaticHeightColumnTests: QuickSpec {

    override func spec() {
        var sut: GridViewModel!
        var group: NSCollectionLayoutGroup?

        describe("The layout items generated by GridViewModel with staticHeightColumn style") {
            let itemSpacing: CGFloat = 12
            let lineSpacing: CGFloat = 10
            let itemHeight: CGFloat = 80

            beforeEach {
                let items = (0..<7).map {
                    LayoutTestCellModel(
                        index: $0,
                        style: .staticHeightColumn(3),
                        width: .fixed(100),
                        height: .fixed(itemHeight),
                        itemSpacing: itemSpacing,
                        lineSpacing: lineSpacing,
                        sectionIndex: 0
                    )
                }
                sut = GridViewModel(items: items, hasLoadMore: false)
                group = sut.makeLayoutSection(
                    0,
                    containerContentSize: CGSize(width: 360, height: 640),
                    containerContentInsets: .zero
                )?.group
            }

            it("should create a vertical group with three row groups") {
                await expect { await group?.interItemSpacing }.to(equal(.fixed(lineSpacing)))
                await expect { await group?.layoutSize.widthDimension.isFractionalWidth }.to(beTruthy())
                await expect { await group?.layoutSize.heightDimension.isAbsolute }.to(beTruthy())
                await expect { await group?.layoutSize.heightDimension.dimension }
                    .to(equal(itemHeight * 3 + lineSpacing * 2))
                await expect { await group?.subitems.count }.to(equal(3))
            }

            it("each row group should have the expected height") {
                await expect { await group?.subitems[0].layoutSize.heightDimension.dimension }.to(equal(itemHeight))
                await expect { await group?.subitems[1].layoutSize.heightDimension.dimension }.to(equal(itemHeight))
                await expect { await group?.subitems[2].layoutSize.heightDimension.dimension }.to(equal(itemHeight))
            }
        }
    }
}
