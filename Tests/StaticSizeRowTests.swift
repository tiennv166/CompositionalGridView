import Foundation
import Nimble
import Quick
import UIKit
@testable import CompositionalGridView

final class StaticSizeRowTests: QuickSpec {

    override func spec() {
        var sut: GridViewModel!
        var layout: GridViewLayoutSection?
        var group: NSCollectionLayoutGroup?

        describe("The layout items generated by GridViewModel with staticSizeRow style") {
            let itemSpacing: CGFloat = 12
            let lineSpacing: CGFloat = 10
            let itemWidth: CGFloat = 100
            let itemHeight: CGFloat = 80

            beforeEach {
                let items = (0..<5).map {
                    LayoutTestCellModel(
                        index: $0,
                        style: .staticSizeRow(2),
                        width: .fixed(itemWidth),
                        height: .fixed(itemHeight),
                        itemSpacing: itemSpacing,
                        lineSpacing: lineSpacing,
                        sectionIndex: 0
                    )
                }
                sut = GridViewModel(items: items, hasLoadMore: false)
                layout = sut.makeLayoutSection(
                    0,
                    containerContentSize: CGSize(width: 400, height: 640),
                    containerContentInsets: .zero
                )
                group = layout?.group
            }

            it("should create an orthogonally scrolling horizontal group") {
                expect(layout?.orthogonalScrollingBehavior).to(equal(.continuous))
                await expect { await group?.interItemSpacing }.to(equal(.fixed(itemSpacing)))
                await expect { await group?.layoutSize.widthDimension.isAbsolute }.to(beTruthy())
                await expect { await group?.layoutSize.heightDimension.isAbsolute }.to(beTruthy())
                await expect { await group?.layoutSize.widthDimension.dimension }
                    .to(equal(itemWidth * 3 + itemSpacing * 2))
                await expect { await group?.layoutSize.heightDimension.dimension }
                    .to(equal(itemHeight * 2 + lineSpacing))
                await expect { await group?.subitems.count }.to(equal(3))
            }

            it("the column groups should have expected dimensions") {
                await expect { await group?.subitems[0].layoutSize.widthDimension.dimension }.to(equal(itemWidth))
                await expect { await group?.subitems[1].layoutSize.widthDimension.dimension }.to(equal(itemWidth))
                await expect { await group?.subitems[2].layoutSize.widthDimension.dimension }.to(equal(itemWidth))
                await expect { await group?.subitems[0].layoutSize.heightDimension.dimension }
                    .to(equal(itemHeight * 2 + lineSpacing))
                await expect { await group?.subitems[1].layoutSize.heightDimension.dimension }
                    .to(equal(itemHeight * 2 + lineSpacing))
                await expect { await group?.subitems[2].layoutSize.heightDimension.dimension }
                    .to(equal(itemHeight))
            }
        }
    }
}
