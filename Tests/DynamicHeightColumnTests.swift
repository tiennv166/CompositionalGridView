import Foundation
import Nimble
import Quick
import UIKit
@testable import CompositionalGridView

final class DynamicHeightColumnTests: QuickSpec {

    override func spec() {
        var sut: GridViewModel!
        var group: NSCollectionLayoutGroup?

        describe("The layout items generated by GridViewModel with dynamicHeightColumn style") {
            let itemSpacing: CGFloat = 8
            let lineSpacing: CGFloat = 10
            let estimatedHeight: CGFloat = 100

            beforeEach {
                let items = (0..<5).map {
                    LayoutTestCellModel(
                        index: $0,
                        style: .dynamicHeightColumn(2),
                        width: .fixed(100),
                        height: .estimated(estimatedHeight),
                        itemSpacing: itemSpacing,
                        lineSpacing: lineSpacing,
                        sectionIndex: 0
                    )
                }
                sut = GridViewModel(items: items, hasLoadMore: false)
                group = sut.makeLayoutSection(
                    0,
                    containerContentSize: CGSize(width: 400, height: 640),
                    containerContentInsets: .zero
                )?.group
            }

            it("should create two estimated-height column groups") {
                await expect { await group?.interItemSpacing }.to(equal(.fixed(itemSpacing)))
                await expect { await group?.layoutSize.widthDimension.isFractionalWidth }.to(beTruthy())
                await expect { await group?.layoutSize.heightDimension.isEstimated }.to(beTruthy())
                await expect { await group?.layoutSize.heightDimension.dimension }
                    .to(equal(estimatedHeight * 3 + lineSpacing * 2))
                await expect { await group?.subitems.count }.to(equal(2))
            }

            it("the column groups should keep their estimated heights") {
                await expect { await group?.subitems[0].layoutSize.heightDimension.isEstimated }.to(beTruthy())
                await expect { await group?.subitems[1].layoutSize.heightDimension.isEstimated }.to(beTruthy())
                await expect { await group?.subitems[0].layoutSize.heightDimension.dimension }
                    .to(equal(estimatedHeight * 3 + lineSpacing * 2))
                await expect { await group?.subitems[1].layoutSize.heightDimension.dimension }
                    .to(equal(estimatedHeight * 2 + lineSpacing))
            }
        }
    }
}
