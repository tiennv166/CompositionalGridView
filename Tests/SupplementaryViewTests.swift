import Foundation
import Nimble
import Quick
import UIKit
@testable import CompositionalGridView

final class SupplementaryViewTests: QuickSpec {

    override func spec() {
        var sut: GridViewModel!
        var layout: GridViewLayoutSection?

        describe("The supplementary items generated by GridViewModel") {

            beforeEach {
                let style: GridLayout.GroupStyle = .normal
                let items: [GridItemModelConfigurable] = [
                    SupplementaryHeaderModel(identity: "header", sectionIndex: 0, style: style),
                    LayoutTestCellModel(index: 0, style: style, width: .fit, height: .fixed(50), itemSpacing: 0, lineSpacing: 0, sectionIndex: 0),
                    SupplementaryFooterModel(identity: "footer", sectionIndex: 0, style: style)
                ]
                sut = GridViewModel(items: items, hasLoadMore: false)
                layout = sut.makeLayoutSection(
                    0,
                    containerContentSize: CGSize(width: 320, height: 640),
                    containerContentInsets: .zero
                )
            }

            it("should keep supplementary models separate from section items") {
                expect(sut.sections.count).to(equal(1))
                expect(sut.sections.first?.items.count).to(equal(1))
                expect(sut.sections.first?.supplementaryItems.count).to(equal(2))
            }

            it("should find header and footer by kind") {
                let header = sut.supplementaryItemOfSection(0, kind: UICollectionView.elementKindSectionHeader)
                let footer = sut.supplementaryItemOfSection(0, kind: UICollectionView.elementKindSectionFooter)
                expect(header?.model.isEqualTo(SupplementaryHeaderModel(identity: "header", sectionIndex: 0, style: .normal))).to(beTruthy())
                expect(footer?.model.isEqualTo(SupplementaryFooterModel(identity: "footer", sectionIndex: 0, style: .normal))).to(beTruthy())
            }

            it("should create pinned header and footer boundary items") {
                expect(layout?.boundarySupplementaryItems.count).to(equal(2))
                let header = layout?.boundarySupplementaryItems.first(where: { $0.elementKind == UICollectionView.elementKindSectionHeader })
                let footer = layout?.boundarySupplementaryItems.first(where: { $0.elementKind == UICollectionView.elementKindSectionFooter })
                expect(header?.alignment).to(equal(.top))
                expect(footer?.alignment).to(equal(.bottom))
                expect(header?.pinToVisibleBounds).to(beTrue())
                expect(footer?.pinToVisibleBounds).to(beTrue())
            }
        }
    }
}
