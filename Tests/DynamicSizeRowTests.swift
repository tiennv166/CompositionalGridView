import Foundation
import Nimble
import Quick
import UIKit
@testable import CompositionalGridView

final class DynamicSizeRowTests: QuickSpec {

    override func spec() {
        var sut: GridViewModel!
        var layout: GridViewLayoutSection?
        var group: NSCollectionLayoutGroup?

        describe("The layout items generated by GridViewModel with dynamicSizeRow style") {
            let itemSpacing: CGFloat = 12
            let lineSpacing: CGFloat = 10
            let estimatedWidth: CGFloat = 100
            let itemHeight: CGFloat = 80

            beforeEach {
                let items = (0..<5).map {
                    LayoutTestCellModel(
                        index: $0,
                        style: .dynamicSizeRow(2),
                        width: .estimated(estimatedWidth),
                        height: .fixed(itemHeight),
                        itemSpacing: itemSpacing,
                        lineSpacing: lineSpacing,
                        sectionIndex: 0
                    )
                }
                sut = GridViewModel(items: items, hasLoadMore: false)
                layout = sut.makeLayoutSection(
                    0,
                    containerContentSize: CGSize(width: 400, height: 640),
                    containerContentInsets: .zero
                )
                group = layout?.group
            }

            it("should create an orthogonally scrolling vertical group with estimated width") {
                expect(layout?.orthogonalScrollingBehavior).to(equal(.continuous))
                await expect { await group?.interItemSpacing }.to(equal(.fixed(lineSpacing)))
                await expect { await group?.layoutSize.widthDimension.isEstimated }.to(beTruthy())
                await expect { await group?.layoutSize.heightDimension.isAbsolute }.to(beTruthy())
                await expect { await group?.layoutSize.widthDimension.dimension }
                    .to(equal(estimatedWidth * 3 + itemSpacing * 2))
                await expect { await group?.layoutSize.heightDimension.dimension }
                    .to(equal(itemHeight * 2 + lineSpacing))
                await expect { await group?.subitems.count }.to(equal(2))
            }

            it("the row groups should keep their estimated widths") {
                await expect { await group?.subitems[0].layoutSize.widthDimension.isEstimated }.to(beTruthy())
                await expect { await group?.subitems[1].layoutSize.widthDimension.isEstimated }.to(beTruthy())
                await expect { await group?.subitems[0].layoutSize.widthDimension.dimension }
                    .to(equal(estimatedWidth * 3 + itemSpacing * 2))
                await expect { await group?.subitems[1].layoutSize.widthDimension.dimension }
                    .to(equal(estimatedWidth * 2 + itemSpacing))
            }
        }
    }
}
